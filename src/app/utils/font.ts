export function getTextGrid(text: string): { active: boolean, colorIndex: number }[][] {
  const upper = text.toUpperCase();
  const rows: { active: boolean, colorIndex: number }[][] = Array.from({ length: 7 }, () => []);
  
  for (let i = 0; i < upper.length; i++) {
    const char = upper[i];
    const matrix = FONT[char] || FONT[' '];
    
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < matrix[r].length; c++) {
        rows[r].push({
          active: matrix[r][c] === 1,
          colorIndex: Math.floor(Math.random() * 5)
        });
      }
      // Add a space between letters
      if (i < upper.length - 1) {
        rows[r].push({ active: false, colorIndex: 0 });
      }
    }
  }
  
  return rows;
}
